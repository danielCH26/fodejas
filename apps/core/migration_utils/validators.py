"""Validadores para la migración de datos legacy (CHG-099)."""
from __future__ import annotations

import csv
import re
from pathlib import Path
from typing import Iterable

# Patterns that indicate raw PII in a column that SHOULD be anonymized.
# The validation intentionally errs on the side of caution: any match
# aborts the migration.

_EMAIL_RE = re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$")
_DOCUMENTO_RE = re.compile(r"^\d{7,10}$")
_TELEFONO_RE = re.compile(r"^\d{10}$")

# Allowlist of safe prefixes used by the test fixtures. These are
# explicitly NOT PII — they are anonymized values generated by the
# factories.
_SAFE_PREFIXES = ("anon-test-",)


def _is_pii(value: str) -> bool:
    """Return True if a string looks like raw PII."""
    if not isinstance(value, str):
        return False
    stripped = value.strip()
    if not stripped:
        return False
    # Allowlist bypasses.
    if any(stripped.startswith(p) for p in _SAFE_PREFIXES):
        return False
    return bool(
        _EMAIL_RE.match(stripped)
        or _DOCUMENTO_RE.match(stripped)
        or _TELEFONO_RE.match(stripped)
    )


def validate_schema(filepath: Path, expected_headers: Iterable[str]) -> list[str]:
    """Check that a CSV file has exactly the expected headers.

    Args:
        filepath: path to the CSV file.
        expected_headers: iterable of header names.

    Returns:
        List of error strings (empty if valid).
    """
    errors: list[str] = []
    if not filepath.exists():
        return [f"archivo no encontrado: {filepath}"]
    with open(filepath, encoding="utf-8", newline="") as f:
        reader = csv.reader(f)
        try:
            actual = next(reader)
        except StopIteration:
            return [f"archivo vacío: {filepath}"]
    expected = list(expected_headers)
    missing = [h for h in expected if h not in actual]
    extra = [h for h in actual if h not in expected]
    if missing:
        errors.append(
            f"{filepath.name}: columnas faltantes: {sorted(missing)}"
        )
    if extra:
        errors.append(
            f"{filepath.name}: columnas no esperadas: {sorted(extra)}"
        )
    return errors


def validate_no_pii(
    filepath: Path,
    pii_columns: Iterable[str],
) -> list[str]:
    """Check that columns declared as anonymized don't contain raw PII.

    Args:
        filepath: path to the CSV file.
        pii_columns: iterable of column names that should be anonymized.

    Returns:
        List of error strings (one per offending row+column).
    """
    errors: list[str] = []
    with open(filepath, encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for row_num, row in enumerate(reader, start=2):
            for col in pii_columns:
                if col not in row:
                    continue
                value = row[col]
                if _is_pii(value):
                    errors.append(
                        f"{filepath.name}:{row_num}:{col}: "
                        f"PII crudo detectado ({value!r}); "
                        f"anonimizar antes de la migración"
                    )
    return errors


def validate_fk_resolution(
    rows: list[dict],
    foreign_key: str,
    lookup: set,
) -> list[str]:
    """Check that every value of `foreign_key` in `rows` exists in `lookup`.

    Args:
        rows: list of dicts (one per CSV row).
        foreign_key: column name to validate.
        lookup: set of acceptable foreign key values.

    Returns:
        List of error strings (one per missing FK).
    """
    errors: list[str] = []
    for idx, row in enumerate(rows, start=2):
        value = row.get(foreign_key, "").strip()
        if value and value not in lookup:
            errors.append(
                f"row {idx}: {foreign_key}={value!r} no existe en lookup"
            )
    return errors
